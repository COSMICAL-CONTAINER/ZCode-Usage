#!/bin/bash
# ============================================================================
# 文件作用：ZCode SessionStart 钩子调用的启动器
#
# 行为：
#   - 应用没运行  -> 启动它，面板自动弹出
#   - 应用已运行  -> 触发一次 reopen，面板重新弹出（幂等，可重复调用）
#
# 为什么这样做：
#   - 钩子是同步阻塞的，必须瞬间返回，所以只做一次 `open -g` 就退出
#   - `-g` 表示不把应用带到前台，保证 ZCode 窗口焦点不被抢走
#   - 无论成功失败都 exit 0，绝不阻塞 ZCode 会话启动
# ============================================================================

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP="$DIR/ZCodeUsageHUD.app"

[ -d "$APP" ] || exit 0

/usr/bin/open -g "$APP" >/dev/null 2>&1

exit 0
